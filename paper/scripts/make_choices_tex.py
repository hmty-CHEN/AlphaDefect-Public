"""从 .notes/data/choice_stats.json 生成附录的两张表（sections/appendix_choices_tables.tex），数字不经手抄。"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
S = json.loads((HERE.parent / "data/choice_stats.json").read_text())
ORDER = ["Defect", "Regent", "Silent", "Fool", "Ironclad", "Necrobinder"]
pct = lambda x: f"{100 * x:.0f}"

rows1 = []
for c in ORDER:
    s = S[c]; pr = s["per_run"]
    sk = s["skip_rate_by_act"]
    rows1.append(f"{c} & {s['card_screens_per_run']:.1f} & {pct(sk[0])}, {pct(sk[1])}, {pct(sk[2])} & {s['spearman_vs_players']:.2f} ({s['n_cards_compared']}) & "
                 f"{pr['shop_card_buys']:.1f} & {pr['card_removals']:.1f} & {pct(pr['smith_share_at_rest'])} & {pr['potions_taken']:.1f}, {pr['potions_discarded']:.1f} \\\\")

def cards(lst):
    return "; ".join(f"{n} {a:.0f}/{h:.0f}" for n, a, h in lst)

rows2 = []
for c in ORDER:
    s = S[c]
    rows2.append(f"{c} & {cards(s['more_than_players'][:3])} & {cards(s['less_than_players'][:3])} \\\\")

def relics(lst):
    return ", ".join(n for n, r, o in lst)

rows3 = []
for c in ORDER:
    s = S[c]
    rows3.append(f"{c} & {s['ancient_n']} & {s['ancient_always']} & {s['ancient_never']} & {relics(s['ancient_top'][:3])} & {relics(s['ancient_low'][:3])} \\\\")

out = r"""% Generated by .notes/scripts/make_choices_tex.py from .notes/data/choice_stats.json (do not edit by hand).
\begin{table}[ht]
\centering
\footnotesize
\setlength{\tabcolsep}{4pt}
\caption{Choices outside combat in the last 4,608 routine-evaluation games of each training run. Screens: card-reward screens per run. Skipped: share of those screens on which no card was taken, in Acts~1, 2 and~3 (\%). $\rho$: rank correlation between the network's and the players' pick rates over the cards offered at least 50 times to the network and 200 times to players (number of cards). Shop: cards bought and cards removed per run. Upgrade: upgrades as a share of upgrades and heals at rest sites (\%). Potions: taken and discarded per run.}
\label{tab:choices}
\smallskip
\begin{tabular}{lccccccc}
\toprule
 & Screens & Skipped & $\rho$ & Shop buys & Removals & Upgrade & Potions \\
\midrule
""" + "\n".join(rows1) + r"""
\bottomrule
\end{tabular}
\end{table}

\begin{table}[ht]
\centering
\footnotesize
\caption{Cards that the networks pick much more or much less often than players, among the cards compared in Table~\ref{tab:choices}: the network's pick rate / the players' (\%).}
\label{tab:choices-cards}
\smallskip
\begin{tabular}{>{\raggedright\arraybackslash}p{0.14\linewidth}>{\raggedright\arraybackslash}p{0.38\linewidth}>{\raggedright\arraybackslash}p{0.38\linewidth}}
\toprule
 & Picked more often & Picked less often \\
\midrule
""" + "\n".join(rows2) + r"""
\bottomrule
\end{tabular}
\end{table}

\begin{table}[ht]
\centering
\footnotesize
\caption{Relics chosen from the Ancients at the start of each act, over the relics offered at least 100 times to the network (number of relics): how many it always chose, how many it never chose, and examples of each.}
\label{tab:choices-ancients}
\smallskip
\begin{tabular}{lccc>{\raggedright\arraybackslash}p{0.27\linewidth}>{\raggedright\arraybackslash}p{0.27\linewidth}}
\toprule
 & Relics & Always & Never & Always chosen, e.g. & Never chosen, e.g. \\
\midrule
""" + "\n".join(rows3) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
(HERE.parent / "tables").mkdir(exist_ok=True)
(HERE.parent / "tables/appendix_choices_tables.tex").write_text(out)   # paper/tables/ in the public release
print(out)
